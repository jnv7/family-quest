/**
 * Generates `CREDITS.md` from every theme's `credits.json`, grouped by theme and by author.
 * Run `npm run credits` to write it, or `npm run credits -- --check` to fail when the committed
 * file is stale (CI and a unit test do the latter).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

interface Credit {
  file: string;
  author: string;
  source: string;
  licence: string;
}

/** Where the text of each allowed licence is. */
export const LICENCE_LINKS: Record<string, string> = {
  'CC0-1.0': 'https://creativecommons.org/publicdomain/zero/1.0/',
  MIT: 'https://opensource.org/license/mit',
};

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

export function generateCredits(themeIds: readonly string[], themesDir = join('src', 'themes')): string {
  const lines = [
    '# Credits',
    '',
    'Generated by `npm run credits` from the `credits.json` of each theme; do not edit by hand.',
    'Every image shipped with a theme is listed here with its author, source and licence.',
    'Emoji are drawn by each phone\'s system font and need no credit.',
    '',
  ];
  for (const themeId of [...themeIds].sort(compare)) {
    const file = join(themesDir, themeId, 'credits.json');
    const credits = (JSON.parse(readFileSync(file, 'utf8')) as { assets: Credit[] }).assets;
    lines.push(`## Theme \`${themeId}\``, '');
    const authors = [...new Set(credits.map((credit) => credit.author))].sort(compare);
    for (const author of authors) {
      lines.push(`### ${author}`, '');
      for (const credit of credits.filter((c) => c.author === author).sort((a, b) => compare(a.file, b.file))) {
        const link = LICENCE_LINKS[credit.licence];
        if (!link) throw new Error(`${file}: no link for the licence "${credit.licence}"`);
        lines.push(`- \`${credit.file}\`: [${credit.licence}](${link}), [source](${credit.source})`);
      }
      lines.push('');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const readThemeIds = (): string[] => JSON.parse(readFileSync(join('scripts', 'validated-themes.json'), 'utf8')) as string[];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const generated = generateCredits(readThemeIds());
  if (process.argv.includes('--check')) {
    if (readFileSync('CREDITS.md', 'utf8') !== generated) {
      console.error('CREDITS.md is out of date; run `npm run credits` and commit it.');
      process.exit(1);
    }
    console.log('credits: CREDITS.md is up to date');
  } else {
    writeFileSync('CREDITS.md', generated);
    console.log('credits: CREDITS.md written');
  }
}
